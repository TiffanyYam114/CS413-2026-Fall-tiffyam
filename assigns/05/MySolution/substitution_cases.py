"""Shared examples with exact expected outputs for both substitution suites."""

from lambda1_vp import (
    D0Eint as Int, D0Ebtf as Bool, D0Evar as Var,
    D0Eop1 as Unary, D0Eop2 as Binary, D0Elam as Lam, D0Efix as Fix,
    D0Eapp as App, D0Eif0 as If, D0Elet as Let,
    D0Epair as Pair, D0Epfst as Fst, D0Epsnd as Snd,
)

x, y, z, f, n = (Var(name) for name in ("x", "y", "z", "f", "n"))

# (expression, substitution target, replacement, expected pretty output)
CASES = [
    (Int(-42), "x", y, "-42"),
    (Bool(True), "x", y, "true"),
    (Bool(False), "x", y, "false"),
    (x, "x", Int(3), "3"),
    (z, "x", Int(3), "z"),
    (x, "x", Binary("+", x, Int(1)), "(x + 1)"),
    (Unary("custom", x), "x", Int(3), "(custom 3)"),
    (Binary("+", x, z), "x", Int(3), "(3 + z)"),
    (App(x, x), "x", Int(3), "(3 3)"),
    (If(x, x, x), "x", Bool(False), "(if false then false else false)"),
    (Pair(x, x), "x", Int(3), "(pair 3 3)"),
    (Fst(x), "x", Pair(Int(1), Int(2)), "(fst (pair 1 2))"),
    (Snd(x), "x", Pair(Int(1), Int(2)), "(snd (pair 1 2))"),
    (Lam("z", x), "x", Int(3), "(lam z. 3)"),
    (Fix("f", "n", x), "x", Int(3), "(fix f(n). 3)"),
    (Let("z", x, x), "x", Int(3), "(let z = 3 in 3)"),
    (Lam("x", Binary("+", x, y)), "x", Int(3), "(lam x. (x + y))"),
    (Fix("x", "n", x), "x", y, "(fix x(n). x)"),
    (Fix("f", "x", x), "x", y, "(fix f(x). x)"),
    (Fix("x", "x", x), "x", y, "(fix x(x). x)"),
    (Let("x", x, Binary("+", x, y)), "x", Int(3), "(let x = 3 in (x + y))"),
    (Lam("y", Binary("+", x, y)), "x", y, "(lam y_1. (y + y_1))"),
    (Let("y", x, Binary("+", x, y)), "x", y, "(let y_1 = y in (y + y_1))"),
    (Fix("f", "n", Binary("+", x, App(f, n))), "x", f,
     "(fix f_1(n). (f + (f_1 n)))"),
    (Fix("f", "n", Pair(x, App(f, n))), "x", n,
     "(fix f(n_1). (pair n (f n_1)))"),
    (Fix("f", "n", Pair(x, App(f, n))), "x", Pair(f, n),
     "(fix f_1(n_1). (pair (pair f n) (f_1 n_1)))"),
    (Fix("f", "f", Pair(x, f)), "x", f,
     "(fix f_1(f_1). (pair f f_1))"),
    (Lam("y", y), "x", y, "(lam y. y)"),
    (Lam("y", Lam("x", x)), "x", y, "(lam y. (lam x. x))"),
    (Fix("f", "n", App(f, n)), "x", Pair(f, n), "(fix f(n). (f n))"),
    (Let("y", x, y), "x", y, "(let y = y in y)"),
    (Let("y", y, Pair(x, y)), "x", y, "(let y_1 = y in (pair y y_1))"),
    (Lam("y", Pair(x, Lam("y", y))), "x", y,
     "(lam y_1. (pair y (lam y. y)))"),
    (Lam("y", Let("y", y, Pair(x, y))), "x", y,
     "(lam y_1. (let y_2 = y_1 in (pair y y_2)))"),
    (Lam("y", Pair(x, Fix("y", "n", y))), "x", y,
     "(lam y_1. (pair y (fix y(n). y)))"),
    (Lam("y", Pair(x, Fix("f", "y", y))), "x", y,
     "(lam y_1. (pair y (fix f(y). y)))"),
    (Lam("y", Pair(x, Lam("y_1", Int(0)))), "x", y,
     "(lam y_2. (pair y (lam y_1. 0)))"),
    (Pair(Lam("y", x), Lam("y", x)), "x", y,
     "(pair (lam y_1. y) (lam y_2. y))"),
    (Pair(Lam("y", x), Var("y_1")), "x", y,
     "(pair (lam y_2. y) y_1)"),
    (Lam("y", x), "x", Pair(y, Lam("y_1", Int(0))),
     "(lam y_2. (pair y (lam y_1. 0)))"),
    (Lam("y", Pair(Var("y_1"), y)), "y_1", y,
     "(lam y_2. (pair y y_2))"),
    (Lam("y", x), "x", Lam("y", y), "(lam y. (lam y. y))"),
    (Binary("/", x, Int(0)), "x", Int(1), "(1 / 0)"),
    (x, "x", Binary("/", Int(1), Int(0)), "(1 / 0)"),
    # Distinct children catch swapping, skipped children, and wrong field use.
    (Binary("-", z, x), "x", Int(3), "(z - 3)"),
    (App(f, x), "x", Int(3), "(f 3)"),
    (Pair(z, x), "x", Int(3), "(pair z 3)"),
    (If(x, Int(1), Int(2)), "x", Bool(True), "(if true then 1 else 2)"),
    (If(Bool(False), x, Int(2)), "x", Int(3), "(if false then 3 else 2)"),
    (If(Bool(False), Int(1), x), "x", Int(3), "(if false then 1 else 3)"),
    # Both enclosing binders conflict, even though the inner one shadows y.
    (Lam("y", Lam("y", Pair(x, y))), "x", y,
     "(lam y_1. (lam y_2. (pair y y_2)))"),
    # Names in later siblings and unused fix/let binders must be reserved.
    (Pair(Lam("y", x), Lam("y_1", z)), "x", y,
     "(pair (lam y_2. y) (lam y_1. z))"),
    (Pair(Lam("y", x), Fix("y_1", "y_2", Int(0))), "x", y,
     "(pair (lam y_3. y) (fix y_1(y_2). 0))"),
    (Lam("y", x), "x", Pair(y, Let("y_1", Int(0), Int(1))),
     "(lam y_2. (pair y (let y_1 = 0 in 1)))"),
    # Generated names are shared across a let initializer and its body.
    (Let("y", Lam("y", x), Lam("y", x)), "x", y,
     "(let y_2 = (lam y_1. y) in (lam y_3. y))"),
    # A conflicting replacement can itself contain the target; insert it once.
    (Lam("y", Pair(x, y)), "x", Pair(x, y),
     "(lam y_1. (pair (pair x y) y_1))"),
]
